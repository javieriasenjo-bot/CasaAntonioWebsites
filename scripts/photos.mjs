// Photo pipeline: photos-src/<stem>.jpg -> public/photos/<stem>-<width>.{avif,webp} + src/lib/photo-manifest.ts
//
//   npm run photos                       generate missing variants, rewrite the manifest
//   npm run photos -- --force            regenerate every variant (changes every photo URL's bytes)
//   npm run photos -- --only=living,sofa limit to some stems
//
// New stems get widths 400/800/1600/max (max = original width, capped at 2000). Existing stems keep
// their current widths and only gain missing ones (e.g. 400). Use a new stem when replacing a photo:
// photos are cached for seven days, so overwriting a URL can show returning guests the old image.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("..", import.meta.url));
const srcDir = join(root, "photos-src");
const outDir = join(root, "public", "photos");
const manifestFile = join(root, "src", "lib", "photo-manifest.ts");
const args = process.argv.slice(2);
const force = args.includes("--force");
const only = args.find((arg) => arg.startsWith("--only="))?.slice(7).split(",").filter(Boolean);
const BASE_WIDTHS = [400, 800, 1600];
const MAX_WIDTH = 2000;
const FORMATS = { avif: { quality: 68, effort: 4 }, webp: { quality: 82, effort: 4 } };
const VARIANT = /^(.+)-(\d+)\.(avif|webp)$/;

function existingWidths() {
  const map = new Map();
  for (const file of readdirSync(outDir)) {
    const match = VARIANT.exec(file);
    if (!match) continue;
    const widths = map.get(match[1]) ?? new Set();
    widths.add(Number(match[2]));
    map.set(match[1], widths);
  }
  return map;
}

const before = existingWidths();
let written = 0;
for (const file of readdirSync(srcDir).filter((name) => /\.jpe?g$/i.test(name)).sort()) {
  const stem = file.replace(/\.jpe?g$/i, "");
  if (only && !only.includes(stem)) continue;
  const source = sharp(join(srcDir, file)).rotate();
  const { width: originalWidth = 0 } = await source.metadata();
  const current = before.get(stem);
  const widths = new Set(current ?? [...BASE_WIDTHS, Math.min(originalWidth, MAX_WIDTH)]);
  widths.add(400);
  for (const width of [...widths].filter((w) => w <= originalWidth).sort((a, b) => a - b)) {
    for (const [ext, options] of Object.entries(FORMATS)) {
      const target = join(outDir, `${stem}-${width}.${ext}`);
      if (!force && existsSync(target)) continue;
      await source.clone().resize({ width, withoutEnlargement: true })[ext](options).toFile(target);
      written += 1;
    }
  }
}

// The manifest always reflects the files on disk, so it cannot drift from public/photos.
const lines = [];
for (const [stem, set] of [...existingWidths()].sort(([a], [b]) => a.localeCompare(b))) {
  const widths = [...set].sort((a, b) => a - b);
  const largest = widths[widths.length - 1];
  for (const w of widths) {
    for (const ext of Object.keys(FORMATS)) {
      if (!existsSync(join(outDir, `${stem}-${w}.${ext}`))) throw new Error(`Missing ${stem}-${w}.${ext}`);
    }
  }
  const { width, height } = await sharp(join(outDir, `${stem}-${largest}.webp`)).metadata();
  lines.push(`  ${JSON.stringify(stem)}: { widths: [${widths.join(", ")}], width: ${width}, height: ${height} },`);
}

writeFileSync(manifestFile, `// Generated by scripts/photos.mjs from the files in public/photos. Do not edit by hand.
export const photoMeta: Record<string, { widths: readonly number[]; width: number; height: number }> = {
${lines.join("\n")}
};

export function photoFile(stem: string, width: number, ext: "avif" | "webp") {
  return \`/photos/\${stem}-\${width}.\${ext}\`;
}
`);
console.log(`Wrote ${written} photo variant(s); manifest lists ${lines.length} photos.`);
